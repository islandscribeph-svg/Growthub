#!/usr/bin/env node
/**
 * Packs the Vite build (dist/) into a Cloudflare Worker.
 *
 * One self-contained worker.js when the gzipped script is within about 9 MB.
 * Past that, a small worker.js plus a kv/ tree whose keys are URL paths.
 * The Worker reads those from a KV binding named ASSETS_KV.
 *
 * Does not deploy. Run `npm run build` first.
 *   node scripts/build-worker.mjs [--dist <dir>] [--out <dir>]
 */

import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const COMPRESSED_LIMIT_BYTES = 9 * 1024 * 1024;

/** Text files are embedded as JavaScript strings. Everything else is base64. */
const TEXT_EXTENSIONS = new Set(['css', 'html', 'js', 'json', 'map', 'mjs', 'svg', 'tmx', 'tsx', 'txt', 'xml']);

const CONTENT_TYPES = {
  css: 'text/css; charset=utf-8',
  flac: 'audio/flac',
  gif: 'image/gif',
  html: 'text/html; charset=utf-8',
  ico: 'image/x-icon',
  jpeg: 'image/jpeg',
  jpg: 'image/jpeg',
  js: 'text/javascript; charset=utf-8',
  json: 'application/json; charset=utf-8',
  m4a: 'audio/mp4',
  map: 'application/json',
  mjs: 'text/javascript; charset=utf-8',
  mp3: 'audio/mpeg',
  ogg: 'audio/ogg',
  png: 'image/png',
  svg: 'image/svg+xml',
  tmx: 'application/xml; charset=utf-8',
  tsx: 'application/xml; charset=utf-8',
  txt: 'text/plain; charset=utf-8',
  wasm: 'application/wasm',
  wav: 'audio/wav',
  webm: 'video/webm',
  webp: 'image/webp',
  woff: 'font/woff',
  woff2: 'font/woff2',
  xml: 'application/xml; charset=utf-8',
};

const gameRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/**
 * Vite's emitted files live in dist/assets and end in a content hash
 * (for example assets/main-CV4QplNH.js). Painted pictures and maps do not.
 * A hash is mixed-case, or contains a digit or underscore, so a long
 * English word such as "courtyard" is not treated as one.
 */
function isHashedAsset(key) {
  if (!key.startsWith('assets/')) return false;
  const base = key.slice(key.lastIndexOf('/') + 1);
  const match = /^(.+)-([A-Za-z0-9_-]{8,})(?:\.[A-Za-z0-9]+)+$/.exec(base);
  if (!match) return false;
  const hash = match[2];
  const mixedCase = /[A-Z]/.test(hash) && /[a-z]/.test(hash);
  return mixedCase || /[0-9_]/.test(hash);
}

function cacheControlFor(key) {
  if (key.toLowerCase().endsWith('.html')) return 'no-cache';
  if (isHashedAsset(key)) return 'public, max-age=31536000, immutable';
  return 'public, max-age=3600';
}

function contentTypeFor(key) {
  const slash = key.lastIndexOf('/');
  const dot = key.lastIndexOf('.');
  if (dot <= slash) return 'application/octet-stream';
  const ext = key.slice(dot + 1).toLowerCase();
  return CONTENT_TYPES[ext] ?? 'application/octet-stream';
}

function extensionOf(key) {
  const slash = key.lastIndexOf('/');
  const dot = key.lastIndexOf('.');
  if (dot <= slash) return '';
  return key.slice(dot + 1).toLowerCase();
}

function option(name, fallback) {
  const index = process.argv.indexOf(name);
  if (index === -1) return fallback;
  const value = process.argv[index + 1];
  if (!value || value.startsWith('--')) throw new Error(`${name} needs a path.`);
  return path.resolve(value);
}

async function collectFiles(root) {
  const found = [];
  async function walk(directory) {
    const entries = await readdir(directory, { withFileTypes: true });
    for (const entry of entries) {
      const full = path.join(directory, entry.name);
      if (entry.isDirectory()) await walk(full);
      else if (entry.isFile()) found.push(full);
    }
  }
  await walk(root);
  found.sort();
  return found;
}

function renderWorker(embeddedExpression) {
  const embedded = embeddedExpression ?? 'null';
  return `// Generated by scripts/build-worker.mjs. Regenerate it; do not edit.
// ${embeddedExpression ? 'Assets are embedded in this module.' : 'Assets are read from the ASSETS_KV binding, keyed by URL path.'}

const CONTENT_TYPES = ${JSON.stringify(CONTENT_TYPES)};
const EMBEDDED = ${embedded};

// Copied from scripts/build-worker.mjs so the cache and type rules stay in one place.
${isHashedAsset.toString()}

${cacheControlFor.toString()}

${contentTypeFor.toString()}

function looksLikeFile(key) {
  const name = key.slice(key.lastIndexOf('/') + 1);
  return name.includes('.');
}

function requestKey(url) {
  let pathname;
  try {
    pathname = new URL(url).pathname;
  } catch {
    return { status: 400, message: 'Bad request' };
  }
  let decoded;
  try {
    decoded = decodeURIComponent(pathname);
  } catch {
    return { status: 400, message: 'Bad request' };
  }
  if (decoded.includes('\\\\') || decoded.includes('\\u0000')) return { status: 400, message: 'Bad request' };
  const parts = [];
  for (const part of decoded.split('/')) {
    if (part === '' || part === '.') continue;
    if (part === '..') return { status: 400, message: 'Bad request' };
    parts.push(part);
  }
  return { key: parts.join('/') };
}

function plain(status, message) {
  return new Response(message, {
    status,
    headers: {
      'content-type': 'text/plain; charset=utf-8',
      'cache-control': 'no-store',
    },
  });
}

function fromEmbedded(key) {
  const item = EMBEDDED[key];
  if (item == null) return null;
  if (typeof item === 'string') return new TextEncoder().encode(item);
  const binary = atob(item.b);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  return bytes;
}

async function fromKv(env, key) {
  const kv = env && env.ASSETS_KV;
  if (!kv || typeof kv.get !== 'function') {
    console.error(JSON.stringify({ message: 'ASSETS_KV binding is not configured' }));
    return { error: plain(500, 'ASSETS_KV binding is not configured.') };
  }
  const value = await kv.get(key, { type: 'arrayBuffer' });
  return { bytes: value ? new Uint8Array(value) : null };
}

function assetResponse(request, key, bytes) {
  const headers = new Headers({
    'content-type': contentTypeFor(key),
    'cache-control': cacheControlFor(key),
    'content-length': String(bytes.byteLength),
    'x-content-type-options': 'nosniff',
  });
  return new Response(request.method === 'HEAD' ? null : bytes, { status: 200, headers });
}

async function load(env, key) {
  if (EMBEDDED) return { bytes: fromEmbedded(key) };
  return fromKv(env, key);
}

export default {
  async fetch(request, env) {
    try {
      if (request.method !== 'GET' && request.method !== 'HEAD') {
        return new Response('Method not allowed', {
          status: 405,
          headers: { allow: 'GET, HEAD', 'content-type': 'text/plain; charset=utf-8' },
        });
      }
      const route = requestKey(request.url);
      if (route.status) return plain(route.status, route.message);
      const key = route.key === '' ? 'index.html' : route.key;
      const found = await load(env, key);
      if (found.error) return found.error;
      if (found.bytes) return assetResponse(request, key, found.bytes);
      if (key !== 'index.html' && !looksLikeFile(key)) {
        const home = await load(env, 'index.html');
        if (home.error) return home.error;
        if (home.bytes) return assetResponse(request, 'index.html', home.bytes);
      }
      return plain(404, 'Not found');
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      console.error(JSON.stringify({ message: 'asset request failed', error: message }));
      return plain(500, 'The palace files could not be read.');
    }
  },
};
`;
}

function embeddedExpression(records) {
  const lines = records.map((record) => {
    const key = JSON.stringify(record.path);
    if (TEXT_EXTENSIONS.has(extensionOf(record.path))) {
      return `  ${key}: ${JSON.stringify(record.body.toString('utf8'))}`;
    }
    return `  ${key}: { b: ${JSON.stringify(record.body.toString('base64'))} }`;
  });
  return `{\n${lines.join(',\n')}\n}`;
}

async function main() {
  const distDir = option('--dist', path.join(gameRoot, 'dist'));
  const outDir = option('--out', path.join(gameRoot, 'cloudflare-dist'));

  let paths;
  try {
    paths = await collectFiles(distDir);
  } catch (error) {
    const code = error && typeof error === 'object' && 'code' in error ? error.code : '';
    if (code === 'ENOENT') throw new Error(`No client build at ${distDir}. Run npm run build first.`);
    throw error;
  }
  if (!paths.some((full) => path.relative(distDir, full).split(path.sep).join('/') === 'index.html')) {
    throw new Error(`${distDir} has no index.html. Run npm run build first.`);
  }

  const records = [];
  for (const full of paths) {
    const rel = path.relative(distDir, full).split(path.sep).join('/');
    const body = await readFile(full);
    if (rel.startsWith('assets/') && !isHashedAsset(rel)) {
      throw new Error(`${rel} is in Vite's assets folder but was not recognised as a hashed file.`);
    }
    records.push({
      path: rel,
      bytes: body.byteLength,
      sha256: createHash('sha256').update(body).digest('hex'),
      contentType: contentTypeFor(rel),
      cacheControl: cacheControlFor(rel),
      body,
    });
  }

  const embeddedWorker = renderWorker(embeddedExpression(records));
  const embeddedWorkerBytes = Buffer.byteLength(embeddedWorker);
  const embeddedWorkerGzipBytes = gzipSync(embeddedWorker).byteLength;
  const kvNeeded = embeddedWorkerGzipBytes > COMPRESSED_LIMIT_BYTES;
  const workerSource = kvNeeded ? renderWorker(null) : embeddedWorker;

  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });
  const workerPath = path.join(outDir, 'worker.js');
  await writeFile(workerPath, workerSource);

  if (kvNeeded) {
    for (const record of records) {
      const destination = path.join(outDir, 'kv', ...record.path.split('/'));
      await mkdir(path.dirname(destination), { recursive: true });
      await writeFile(destination, record.body);
    }
  }

  const checked = spawnSync(process.execPath, ['--check', workerPath], { encoding: 'utf8' });
  if (checked.status !== 0) {
    throw new Error(checked.stderr || 'worker.js failed the syntax check.');
  }

  const workerBytes = Buffer.byteLength(workerSource);
  const manifest = {
    mode: kvNeeded ? 'kv' : 'embedded',
    kvNeeded,
    kvBinding: kvNeeded ? 'ASSETS_KV' : null,
    compressedLimitBytes: COMPRESSED_LIMIT_BYTES,
    embeddedWorkerBytes,
    embeddedWorkerGzipBytes,
    workerBytes,
    workerSha256: createHash('sha256').update(workerSource).digest('hex'),
    fileCount: records.length,
    totalBytes: records.reduce((sum, record) => sum + record.bytes, 0),
    files: records.map((record) => ({
      path: record.path,
      bytes: record.bytes,
      sha256: record.sha256,
      contentType: record.contentType,
      cacheControl: record.cacheControl,
    })),
  };
  await writeFile(path.join(outDir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);

  const kib = (bytes) => `${(bytes / 1024).toFixed(1)} KiB`;
  const mib = (bytes) => `${(bytes / (1024 * 1024)).toFixed(2)} MiB`;
  console.log(`Embedded worker would be ${mib(embeddedWorkerBytes)} (${mib(embeddedWorkerGzipBytes)} gzip).`);
  console.log(`Limit is ${mib(COMPRESSED_LIMIT_BYTES)} gzip, so KV is ${kvNeeded ? 'required' : 'not required'}.`);
  console.log(`Wrote ${workerPath} (${kib(workerBytes)}).`);
  if (kvNeeded) console.log(`Wrote ${records.length} assets (${mib(manifest.totalBytes)}) to ${path.join(outDir, 'kv')}.`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
